"""Render app.yml from the bundle variables, then run `apx build`.

Called by the bundle artifact build (databricks.yml) with the interpolated variables, so
the deployed app's runtime config always matches the bundle. Can also be run by hand:

    python3 scripts/build_app.py --lakebase-endpoint=projects/<p>/branches/<b>/endpoints/<e> \
        --synced-schema=<schema> --app-schema=<schema> [--genie-space-id=<id>]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_IDENT = re.compile(r"^[a-z_][a-z0-9_]*$")
_ENDPOINT = re.compile(r"^projects/[a-z][a-z0-9-]*/branches/[a-z][a-z0-9-]*/endpoints/[a-z][a-z0-9-]*$")


def render(args: argparse.Namespace) -> str:
    def env(name: str, value: str) -> str:
        return f'  - name: "{name}"\n    value: {json.dumps(value)}\n'

    return (
        "# GENERATED by scripts/build_app.py from the variables in databricks.yml — edit those, not this file.\n"
        "# AUDITOR_APP_* env vars map to AppConfig fields (backend/core/_config.py). The `postgres` app\n"
        "# resource injects PGHOST / PGUSER / PGDATABASE / PGPORT for the app service principal.\n"
        'command: ["uvicorn", "auditor_app.backend.app:app", "--host", "0.0.0.0", "--port", "8000"]\n'
        "\n"
        "env:\n"
        + env("AUDITOR_APP_LAKEBASE_ENDPOINT", args.lakebase_endpoint)
        + env("AUDITOR_APP_LAKEBASE_DATABASE", args.postgres_database)
        + env("AUDITOR_APP_SYNCED_SCHEMA", args.synced_schema)
        + env("AUDITOR_APP_APP_SCHEMA", args.app_schema)
        + env("AUDITOR_APP_GENIE_SPACE_ID", args.genie_space_id)
        + env("AUDITOR_APP_PII_GROUPS", args.pii_groups)
        + "  # Foundation Model endpoint for document-request drafts (app resource `draft-model`).\n"
        '  - name: "AUDITOR_APP_DRAFT_MODEL"\n'
        '    valueFrom: "draft-model"\n'
    )


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--lakebase-endpoint", required=True)
    p.add_argument("--postgres-database", default="databricks_postgres")
    p.add_argument("--synced-schema", required=True)
    p.add_argument("--app-schema", required=True)
    p.add_argument("--genie-space-id", default="")
    p.add_argument("--pii-groups", default="admins")
    p.add_argument("--skip-apx", action="store_true", help="only render app.yml")
    args = p.parse_args()

    if not _ENDPOINT.match(args.lakebase_endpoint):
        p.error(f"--lakebase-endpoint is not an endpoint resource path: {args.lakebase_endpoint!r}")
    for flag in ("postgres_database", "synced_schema", "app_schema"):
        if not _IDENT.match(getattr(args, flag)):
            p.error(f"--{flag.replace('_', '-')} must be a lowercase Postgres identifier")

    (ROOT / "app.yml").write_text(render(args))
    print(f"Rendered {ROOT / 'app.yml'}")
    if args.skip_apx:
        return 0
    return subprocess.run(["apx", "build"], cwd=ROOT).returncode


if __name__ == "__main__":
    sys.exit(main())

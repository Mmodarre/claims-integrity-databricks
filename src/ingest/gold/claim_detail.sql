-- Auditor claim page header (one row per hospital claim). Contains member identity because an
-- auditor must identify the member; member PII columns are masked by Unity Catalog column masks (mask_pii_*). Lakebase sync source.
CREATE OR REFRESH MATERIALIZED VIEW ${gold_schema}.claim_detail (
  claim_id STRING NOT NULL,
  claim_number STRING,
  claim_status STRING,
  service_date DATE,
  lodgement_date DATE,
  payment_date DATE,
  claim_channel STRING,
  member_id STRING,
  member_number STRING,
  member_full_name STRING MASK ${catalog}.${gold_schema}.mask_pii_string,
  member_dob DATE MASK ${catalog}.${gold_schema}.mask_pii_date,
  member_gender STRING,
  medicare_number STRING MASK ${catalog}.${gold_schema}.mask_pii_string,
  member_state STRING,
  policy_number STRING,
  policy_type STRING,
  product_name STRING,
  admission_id STRING,
  admission_date DATE,
  discharge_date DATE,
  length_of_stay_days BIGINT,
  same_day_flag BOOLEAN,
  admission_type STRING,
  accommodation_type STRING,
  care_type STRING,
  separation_mode STRING,
  drg_code STRING,
  principal_diagnosis_code STRING,
  principal_procedure_code STRING,
  theatre_minutes INT,
  hospital_id BIGINT,
  hospital_code STRING,
  hospital_name STRING,
  region STRING,
  hospital_is_contracted BOOLEAN,
  surgeon_provider_id BIGINT,
  surgeon_name STRING,
  accommodation_charge_aud DECIMAL(7,2),
  theatre_charge_aud DECIMAL(7,2),
  prosthesis_charge_aud DECIMAL(7,2),
  total_claim_amount_aud DECIMAL(7,2),
  benefit_paid_aud DECIMAL(7,2),
  gap_aud DECIMAL(7,2),
  CONSTRAINT claim_id_present EXPECT (claim_id IS NOT NULL) ON VIOLATION DROP ROW
)
COMMENT 'Hospital claim header for the auditor app: claim, member identity, policy, admission, hospital, surgeon. PK: claim_id.'
TBLPROPERTIES ('quality' = 'gold', 'contains_pii' = 'true', 'delta.enableChangeDataFeed' = 'true', 'lakebase.primary_key' = 'claim_id')
AS SELECT
  e.claim_id,
  e.claim_number,
  e.claim_status,
  e.service_date,
  e.lodgement_date,
  c.payment_date,
  c.claim_channel,
  e.member_id,
  m.member_number,
  concat_ws(' ', m.first_name, m.last_name)  AS member_full_name,
  m.date_of_birth                            AS member_dob,
  m.gender                                   AS member_gender,
  m.medicare_number,
  m.state                                    AS member_state,
  p.policy_number,
  p.policy_type,
  prod.product_name,
  e.admission_id,
  e.admission_date,
  e.discharge_date,
  e.length_of_stay_days,
  e.same_day_flag,
  e.admission_type,
  e.accommodation_type,
  e.care_type,
  e.separation_mode,
  e.drg_code,
  e.principal_diagnosis_code,
  e.principal_procedure_code,
  e.theatre_minutes,
  e.hospital_id,
  e.hospital_code,
  e.hospital_name,
  e.region,
  h.is_contracted                            AS hospital_is_contracted,
  e.surgeon_provider_id,
  sp.display_name                            AS surgeon_name,
  e.accommodation_charge_aud,
  e.theatre_charge_aud,
  e.prosthesis_charge_aud,
  e.total_claim_amount_aud,
  e.benefit_paid_aud,
  e.gap_aud
FROM claim_episode e
JOIN claim c               ON c.claim_id = e.claim_id
LEFT JOIN member m         ON m.member_id = e.member_id
LEFT JOIN policy p         ON p.policy_id = e.policy_id
LEFT JOIN product prod     ON prod.product_id = p.product_id
LEFT JOIN hospital h       ON h.hospital_id = e.hospital_id
LEFT JOIN provider sp      ON sp.provider_id = e.surgeon_provider_id;
